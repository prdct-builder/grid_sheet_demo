/// 4px-based spacing scale shared by every feature page's chrome — pick the
/// named step closest to what you need rather than a raw number, so spacing
/// stays consistent across all 23 pages.
abstract final class ThemeSpacing {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 20;
  static const double xxl = 24;
  static const double xxxl = 32;
}
